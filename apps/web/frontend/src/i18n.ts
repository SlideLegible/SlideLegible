const tables: Record<Lang, Record<string, string>> = { "zh-TW": zh, en };

export type Translate = (key: string, params?: Record<string, string | number>) => string;

export function makeTranslator(lang: Lang): Translate {
  return (key, params) => {
    const text = tables[lang][key] ?? tables.en[key] ?? key;
    if (!params) return text;
    return text.replace(/\{(\w+)\}/g, (_, name: string) => String(params[name] ?? `{${name}}`));
  };
}

export const I18nContext = createContext<{ lang: Lang; t: Translate }>({
  lang: "zh-TW",
  t: makeTranslator("zh-TW"),
});

export const useI18n = () => useContext(I18nContext);
